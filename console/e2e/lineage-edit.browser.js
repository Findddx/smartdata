async (page) => {
  const origin = new URL(page.url()).origin;
  if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin)) throw new Error("local rehearsal only");
  page.setDefaultTimeout(45_000);
  const headers = { "X-Demo-Actor": "admin" };
  const getState = async () => (await page.request.get(origin + "/api/v1/workspace", { headers })).json();
  const getMappings = async () => (await page.request.get(origin + "/api/v1/workspace/lineage/mappings", { headers })).json();
  const before = await getState();
  const baseline = await getMappings();
  if (!before.sources.length || !before.sources.every((source) => source.provenance === "DEMO") || baseline.entities.length !== 1 || baseline.entities[0].name !== "客户订单实体") throw new Error("requires the owned, unchanged synthetic lineage rehearsal; reconcile earlier attempts first");
  const original = baseline.entities[0];
  const settle = async () => {
    await page.waitForFunction(() => document.querySelector(".sd-graph-node") || [...document.querySelectorAll("h2")].some((element) => element.textContent === "图谱暂时不可用"), null, { timeout: 45_000 });
    if (await page.getByRole("heading", { name: "图谱暂时不可用", exact: true }).count()) { await page.getByRole("button", { name: "重新读取图谱", exact: true }).click(); await page.locator(".sd-graph-node").first().waitFor(); }
    await page.waitForFunction(() => getComputedStyle(document.querySelector(".sd-page")).opacity === "1");
  };
  const editor = () => page.getByRole("dialog", { name: "登记业务映射", exact: true });
  const openEditor = async () => { await settle(); await page.getByRole("button", { name: "管理映射", exact: true }).click(); await editor().getByRole("textbox", { name: "实体名称", exact: true }).first().waitFor(); };
  const saveEditor = async () => {
    const response = page.waitForResponse((response) => response.request().method() === "POST" && response.url().endsWith("/api/v1/workspace/lineage/mappings"));
    await editor().getByRole("button", { name: "保存声明", exact: true }).click();
    const result = await response;
    if (!result.ok()) throw new Error("UI mapping save rejected: " + result.status());
    await editor().waitFor({ state: "hidden" });
    await settle();
  };
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto(origin + "/#/graph");
  await page.reload();
  await openEditor();
  await editor().getByRole("textbox", { name: "实体名称", exact: true }).first().fill(original.name + " · 界面复核");
  await saveEditor();
  const firstSaved = await getMappings();
  if (firstSaved.version !== baseline.version + 1 || firstSaved.entities[0].name !== original.name + " · 界面复核") throw new Error("real UI update did not persist");
  await openEditor();
  await editor().getByRole("textbox", { name: "实体名称", exact: true }).first().fill("尚未提交的并发核验草稿");
  const concurrentState = await getState();
  const concurrent = await getMappings();
  const conflictResponse = await page.request.post(origin + "/api/v1/workspace/lineage/mappings", { headers: { ...headers, "Idempotency-Key": await page.evaluate(() => crypto.randomUUID()) }, data: { expectedStateVersion: concurrentState.stateVersion, expectedMappingVersion: concurrent.version, entities: concurrent.entities.map((entity) => entity.id === original.id ? { ...entity, name: original.name + " · 另一会话" } : entity), metrics: concurrent.metrics, decisions: concurrent.decisions } });
  if (!conflictResponse.ok()) throw new Error("concurrent rehearsal writer failed: " + conflictResponse.status());
  const rejectedResponse = page.waitForResponse((response) => response.request().method() === "POST" && response.url().endsWith("/api/v1/workspace/lineage/mappings"));
  await editor().getByRole("button", { name: "保存声明", exact: true }).click();
  if ((await rejectedResponse).status() !== 409) throw new Error("stale draft did not receive a real conflict");
  await editor().getByText(/已有更新的映射版本/).waitFor();
  if (await editor().getByRole("textbox", { name: "实体名称", exact: true }).first().inputValue() !== "尚未提交的并发核验草稿") throw new Error("conflict discarded the unsaved draft");
  if (!await editor().getByRole("button", { name: "保存声明", exact: true }).isDisabled()) throw new Error("stale draft could overwrite the new version");
  await page.screenshot({ path: "output/playwright/lineage-conflict-draft.png", animations: "disabled" });
  await editor().getByRole("button", { name: "载入最新映射（替换草稿）", exact: true }).click();
  await editor().getByRole("textbox", { name: "实体名称", exact: true }).first().fill(original.name);
  await saveEditor();
  await openEditor();
  await editor().getByRole("button", { name: "添加实体", exact: true }).click();
  const temporary = editor().locator(".sd-mapping-entry").last();
  await temporary.getByRole("textbox", { name: "实体名称", exact: true }).fill("界面核验临时实体（演示）");
  await temporary.getByRole("textbox", { name: "业务类型", exact: true }).fill("UI_REVIEW_REFERENCE");
  await temporary.getByRole("textbox", { name: "映射与转换说明", exact: true }).fill("这是一项明确的合成核验引用，不执行数据处理，验收后删除。");
  await temporary.getByRole("checkbox").first().waitFor();
  await temporary.getByRole("checkbox").first().check();
  await saveEditor();
  const created = await getMappings();
  if (created.entities.length !== 2) throw new Error("temporary UI entity not created");
  await openEditor();
  await editor().getByRole("button", { name: "移除实体 界面核验临时实体（演示）", exact: true }).click();
  await saveEditor();
  const after = await getState();
  const restored = await getMappings();
  if (restored.entities.length !== 1 || restored.entities[0].name !== original.name || JSON.stringify(restored.entities[0].inputFields) !== JSON.stringify(original.inputFields) || JSON.stringify(restored.metrics) !== JSON.stringify(baseline.metrics) || JSON.stringify(restored.decisions) !== JSON.stringify(baseline.decisions)) throw new Error("rehearsal did not restore the original definitions and dependencies");
  if (after.sources.length !== before.sources.length || !after.sources.every((source) => source.status === "SCANNED" && source.provenance === "DEMO")) throw new Error("rehearsal changed source connections");
  return { result: "PASS_REAL_UI_LINEAGE_CRUD_AND_CONFLICT", initialStateVersion: before.stateVersion, finalStateVersion: after.stateVersion, initialMappingVersion: baseline.version, finalMappingVersion: restored.version, conflictStatus: 409, draftPreserved: true, originalDefinitionsRestored: true, sourcesUnchanged: true, metadataOnly: true };
}
