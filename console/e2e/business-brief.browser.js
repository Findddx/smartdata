async (page) => {
  const check = (value, label) => { if (!value) throw new Error(label); };
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  const origin = new URL(page.url()).origin;
  check(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin), 'only an explicit local workspace is allowed');
  const read = async () => {
    const response = await page.request.get(origin + '/api/v1/workspace', {headers: {'X-Demo-Actor': 'admin'}});
    check(response.ok(), 'workspace must be connected');
    return response.json();
  };
  const initial = await read();
  check(initial.sources.length === 3 && initial.sources.every(source => source.provenance === 'DEMO'), 'requires explicitly loaded, synthetic demonstration sources');
  check(initial.businessBrief === null, 'refuse to overwrite an existing business brief');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin + '/#/business');
  await page.getByRole('textbox', {name:'企业或业务团队名称',exact:true}).fill('示例商贸 · 业务协作演练');
  await page.getByRole('textbox', {name:'业务简介与本次背景',exact:true}).fill('仅使用合成订单、库存和同步记录，演练如何确定目标、安排团队并共同确认口径。');
  await page.getByRole('button', {name:'让分析结果可信',exact:true}).click();
  await page.getByRole('textbox', {name:'目标名称 1',exact:true}).fill('先把订单数据核对清楚');
  await page.getByRole('combobox', {name:'目标优先级 1',exact:true}).selectOption('HIGH');
  const scope = page.getByRole('region', {name:'本轮看哪些来源',exact:true});
  for (const source of initial.sources) await scope.getByRole('checkbox', {name:new RegExp(source.name)}).check();
  await page.getByRole('button',{name:'服务团队',exact:true}).click();
  await page.getByRole('button',{name:'业务约定',exact:true}).click();
  check(await page.getByRole('textbox', {name:'企业或业务团队名称',exact:true}).inputValue() === '示例商贸 · 业务协作演练', 'draft lost across route changes');
  await page.getByRole('button', {name:'登记指标口径',exact:true}).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox',{name:'指标名称',exact:true}).fill('实付销售额');
  await dialog.getByRole('textbox',{name:'业务定义',exact:true}).fill('按支付日归属，不含取消订单；退款按同批订单另行核对。');
  await dialog.getByRole('textbox',{name:'口径负责人',exact:true}).fill('示例业务负责人');
  await dialog.getByRole('combobox',{name:'业务时区',exact:true}).fill('Asia/Shanghai');
  await dialog.getByRole('textbox',{name:'币种（可选）',exact:true}).fill('CNY');
  await dialog.getByRole('textbox',{name:'计算口径说明',exact:true}).fill('按支付日汇总实付金额，扣除同批退款。当前只登记定义，不计算数值。');
  await dialog.getByRole('checkbox',{name:new RegExp(initial.sources[0].name)}).check();
  await dialog.getByRole('button',{name:'加入待保存约定',exact:true}).click();
  await page.getByRole('button',{name:'保存业务约定',exact:true}).first().click();
  await page.getByText('已保存 · 约定 v1', {exact:true}).waitFor();
  let saved = await read();
  check(saved.businessBrief.goals[0].priority === 'HIGH', 'goal priority was not persisted');
  check(saved.businessBrief.metrics[0].status === 'DRAFT', 'unsaved draft forged confirmation');
  check(saved.tasks.some(task => task.inCurrentScope && task.goalIds.includes(saved.businessBrief.goals[0].id)), 'goal did not affect real assistant tasks');
  await page.getByRole('button',{name:'确认口径',exact:true}).click();
  await page.getByText('已保存 · 约定 v2', {exact:true}).waitFor();
  saved = await read();
  check(saved.businessBrief.metrics[0].status === 'CONFIRMED' && saved.businessBrief.metrics[0].confirmedBy === 'admin', 'confirmation not tied to actual local request actor');
  check(saved.businessBrief.metrics[0].calculationStatus === 'NOT_COMPUTED', 'confirmation fabricated a business value');
  await page.getByRole('button',{name:'版本记录',exact:true}).click();
  await page.getByRole('dialog').getByText('v1',{exact:true}).waitFor();
  await page.keyboard.press('Shift+Tab');
  check(await page.evaluate(() => !!document.activeElement.closest('dialog')), 'focus escaped business history dialog');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sd-page')).opacity === '1');
  await page.locator('.sd-toast').waitFor({state:'hidden'});
  await page.screenshot({path:'output/playwright/business-brief-linen-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(() => document.body.scrollWidth <= innerWidth), 'business page overflowed mobile width');
  await page.screenshot({path:'output/playwright/business-brief-linen-mobile.png'});
  await page.getByRole('heading',{name:'同一个数字，同一种理解',exact:true}).scrollIntoViewIfNeeded();
  check(await page.getByText('口径已确认',{exact:true}).isVisible(), 'mobile cannot reach the confirmed metric');
  await page.screenshot({path:'output/playwright/business-brief-metric-mobile.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('button',{name:'打开导航',exact:true}).click();
  await page.getByRole('button',{name:'服务团队',exact:true}).click();
  await page.getByRole('tab',{name:/分析助手/}).click();
  await page.getByText(/目标、公司与口径原文未发送给模型/).waitFor();
  check(await page.getByText(/目标、公司与口径原文未发送给模型/).count() > 0, 'team omitted business context routing boundary');
  check(failures.length === 0, 'browser errors: ' + failures.join('; '));
  console.log(JSON.stringify({result:'PASS_BUSINESS_BRIEF_BROWSER',api:'real loopback Spring service',data:'explicit synthetic demonstration only',businessBriefVersion:saved.businessBrief.version,metricStatus:saved.businessBrief.metrics[0].status,calculationStatus:'NOT_COMPUTED',draftAcrossRoutes:true,historyFocus:true,mobile:'390x844',pageErrors:failures.length}));
}
