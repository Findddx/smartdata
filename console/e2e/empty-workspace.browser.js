async (page) => {
  const check = (value, reason) => { if (!value) throw new Error(reason); };
  const origin = new URL(page.url()).origin;
  check(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin), "local frontend acceptance only");
  const before = await (await page.request.get(origin + "/api/v1/workspace", { headers: { "X-Demo-Actor": "admin" } })).json();
  check(before.sources.length === 0, "requires a genuinely empty workspace; do not reset user data");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.evaluate(() => localStorage.setItem("smartdata.navCollapsed", "false"));
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto(origin + "/#/graph");
  await page.getByRole("heading", { name: "从一份真实数据开始", exact: true }).waitFor();
  if (await page.getByRole("button", { name: "展开导航", exact: true }).count()) await page.getByRole("button", { name: "展开导航", exact: true }).click();
  await page.waitForFunction(() => Math.round(document.querySelector(".sd-sidebar").getBoundingClientRect().width) === 192);
  await page.locator('.sd-graph-art img').evaluate((image) => image.decode());
  check(await page.locator(".sd-graph-node").count() === 0, "empty workspace fabricated nodes");
  await page.screenshot({ path: "output/playwright/islands-empty-desktop.png", animations: "disabled", scale: "css" });
  await page.getByRole("button", { name: "收起导航", exact: true }).click();
  await page.waitForFunction(() => Math.round(document.querySelector(".sd-sidebar").getBoundingClientRect().width) === 52);
  check(await page.getByRole("button", { name: "空间设置", exact: true }).isVisible(), "collapsed settings became unnamed");
  await page.getByRole("button", { name: "展开导航", exact: true }).click();
  await page.keyboard.press("Control+k");
  check(await page.getByRole("combobox", { name: "搜索", exact: true }).evaluate((element) => element === document.activeElement), "command input focus failed");
  await page.getByRole("combobox", { name: "搜索", exact: true }).fill("数据连接");
  await page.keyboard.press("Enter");
  await page.getByRole("heading", { name: "数据连接", exact: true }).waitFor();
  await page.getByRole("button", { name: "添加数据来源", exact: true }).first().click();
  await page.getByRole("dialog", { name: "连接一个数据来源", exact: true }).waitFor();
  await page.keyboard.press("Escape");
  check(await page.getByRole("dialog").count() === 0, "source editor failed to close");
  const mobileContext = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: "reduce" });
  const mobile = await mobileContext.newPage();
  await mobile.goto(origin + "/#/graph");
  await mobile.getByRole("heading", { name: "从一份真实数据开始", exact: true }).waitFor();
  await mobile.locator('.sd-graph-art img').evaluate((image) => image.decode());
  check(await mobile.evaluate(() => document.body.scrollWidth <= innerWidth), "empty mobile workspace overflowed");
  await mobile.screenshot({ path: "output/playwright/islands-empty-mobile.png", animations: "disabled", scale: "css" });
  await mobile.getByRole("button", { name: "打开导航", exact: true }).tap();
  check(await mobile.evaluate(() => document.querySelector(".sd-shell-content").inert), "mobile navigation left the workspace interactive");
  await mobile.getByRole("button", { name: "空间设置", exact: true }).tap();
  await mobile.getByRole("heading", { name: "空间设置", exact: true }).waitFor();
  check(await mobile.evaluate(() => !document.querySelector(".sd-shell-content").inert), "mobile navigation did not release the workspace");
  await mobileContext.close();
  const after = await (await page.request.get(origin + "/api/v1/workspace", { headers: { "X-Demo-Actor": "admin" } })).json();
  check(after.stateVersion === before.stateVersion && after.sources.length === 0, "empty-state acceptance mutated the workspace");
  return { result: "PASS_EMPTY_DESKTOP_AND_TOUCH", stateVersion: after.stateVersion, artworkLoaded: true, keyboardCommand: true, mobile: "390x844", realTouch: true, fabricatedNodes: 0, noWrites: true };
}
