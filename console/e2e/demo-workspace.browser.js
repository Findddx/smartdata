async (page) => {
  const failures = [];
  const check = (value, label) => { if (!value) throw new Error(label); };
  page.on('pageerror', (error) => failures.push(error.message));
  const origin = new URL(page.url()).origin;
  check(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin), 'use an explicit local workspace');
  const response = await page.request.get(origin + '/api/v1/workspace', {headers: {'X-Demo-Actor': 'admin'}});
  check(response.ok(), 'workspace not connected');
  const state = await response.json();
  check(state.sources.length === 3 && state.sources.every(source => source.provenance === 'DEMO'), 'load the explicit commerce demonstration before this read-only acceptance');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin + '/#/settings');
  await page.getByRole('heading', { name: '空间设置' }).waitFor();
  await page.getByRole('button', { name: /水碧 · 月白/ }).click();
  await page.getByRole('button', { name: '工作清单', exact: true }).click();
  await page.getByRole('heading', { name: '工作清单' }).waitFor();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sd-page')).opacity === '1');
  await page.screenshot({path:'output/playwright/workspace-muse-desktop.png'});
  const finding = page.locator('.sd-finding-row').first();
  await finding.click();
  await page.getByRole('dialog').waitFor();
  check(await page.getByText('本次检查依据', {exact:true}).isVisible(), 'evidence panel unavailable');
  await page.keyboard.press('Shift+Tab');
  check(await page.evaluate(() => !!document.activeElement.closest('dialog')), 'focus escaped evidence dialog');
  await page.keyboard.press('Escape');
  check(await page.getByRole('dialog').count() === 0, 'Escape did not close dialog');
  await page.keyboard.press('Control+k');
  await page.getByRole('combobox', {name:'搜索',exact:true}).fill('服务团队');
  await page.keyboard.press('Enter');
  await page.getByRole('heading', {name:'服务团队'}).waitFor();
  await page.getByRole('tab', {name:/运维助手/}).focus();
  await page.keyboard.press('End');
  check(await page.getByRole('tab',{name:/决策助手/}).getAttribute('aria-selected') === 'true', 'keyboard tab selection failed');
  check(await page.getByText('负责：数据分析助手', {exact:true}).count() > 0, 'decision references lost specialist');
  await page.setViewportSize({width:390,height:844});
  for (const name of ['运维助手','分析助手','决策助手']) {
    const box = await page.getByRole('tab',{name:new RegExp(name)}).boundingBox();
    check(box && box.x >= 0 && box.x + box.width <= 390, 'role off screen: ' + name);
  }
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sd-page')).opacity === '1');
  await page.screenshot({path:'output/playwright/workspace-team-mobile-final.png'});
  await page.getByRole('button',{name:'打开导航',exact:true}).click();
  check(await page.evaluate(() => document.querySelector('.sd-shell-content').inert), 'background remained interactive');
  await page.keyboard.press('Shift+Tab');
  check(await page.evaluate(() => !!document.activeElement.closest('aside')), 'focus escaped mobile navigation');
  await page.keyboard.press('Escape');
  check(await page.getByRole('button',{name:'打开导航',exact:true}).evaluate(element => element === document.activeElement), 'navigation did not return focus');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(origin+'/#/overview');
  await page.getByRole('heading',{name:'工作清单'}).waitFor();
  check(await page.locator('animateMotion').count() === 0, 'reduced motion ignored');
  check(await page.evaluate(() => document.body.scrollWidth <= innerWidth), 'mobile horizontal overflow');
  await page.setViewportSize({width:1440,height:1000});
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出报告',exact:true}).click();
  const download = await downloadPromise;
  check(download.suggestedFilename().endsWith('.txt'), 'report not human readable text');
  await page.getByRole('button',{name:'空间设置',exact:true}).click();
  await page.getByRole('heading',{name:'空间设置'}).waitFor();
  await page.getByRole('button',{name:/石墨 · 钛银/}).click();
  await page.getByRole('button',{name:'工作清单',exact:true}).click();
  await page.getByRole('heading',{name:'工作清单'}).waitFor();
  check(await page.locator('.sd-primary').first().evaluate(element => getComputedStyle(element).color) === 'rgb(37, 39, 38)', 'dark theme action contrast incorrect');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sd-page')).opacity === '1');
  await page.screenshot({path:'output/playwright/workspace-titanium-desktop.png'});
  await page.getByRole('button',{name:'空间设置',exact:true}).click();
  await page.getByRole('heading',{name:'空间设置'}).waitFor();
  await page.getByRole('button',{name:/矿白 · 普鲁士蓝/}).click();
  await page.getByRole('button',{name:'工作清单',exact:true}).click();
  await page.getByRole('heading',{name:'工作清单'}).waitFor();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sd-page')).opacity === '1');
  await page.screenshot({path:'output/playwright/workspace-linen-desktop-final.png'});
  check(failures.length === 0, 'page errors: ' + failures.join('; '));
  console.log(JSON.stringify({browser:'Chromium',desktop:'1440x1000',mobile:'390x844',themes:3,evidence:true,searchKeyboard:true,roleKeyboard:true,mobileFocus:true,reducedMotion:true,humanReport:download.suggestedFilename(),pageErrors:failures.length}));
}
